import type { ProductRow } from './apiClient';
import { productImages } from './gallery';

/**
 * Paper and WhatsApp artefacts built from a catalog.
 *
 * These are pure string builders, kept out of the screens so they can be
 * unit-tested: the wholesale pitch is the product's actual sales channel, and
 * a missing price or MOQ line costs the artisan a real order.
 */

/**
 * The bilingual WhatsApp wholesale pitch.
 *
 * Exported and unit-tested: this text is the product's actual sales channel,
 * and a missing price or MOQ line costs the artisan a real order.
 */
export function buildWholesalePitch(product: ProductRow): string {
  return [
    `*${product.title_hi}*`,
    product.title_en,
    '',
    `थोक भाव / Wholesale: ₹${Number(product.recommended_wholesale_inr).toLocaleString(
      'en-IN',
    )} (${product.min_wholesale_qty}+ pcs)`,
    `MRP: ₹${Number(product.recommended_retail_inr).toLocaleString('en-IN')}`,
    `स्टॉक / Stock: ${product.stock_quantity}`,
    product.hsn_code ? `HSN: ${product.hsn_code}` : '',
    `नाप / Size: ${product.dimensions_cm.length} × ${product.dimensions_cm.width} cm`,
    '',
    product.description_en.slice(0, 400),
    '',
    ...productImages(product),
    `SKU: ${product.sku}`,
  ]
    .filter(Boolean)
    .join('\n');
}

/**
 * Bilingual wholesale lookbook.
 *
 * Printed on A4 at a trade fair and forwarded on WhatsApp, so it is laid out
 * for paper: high-contrast on white (not the app's obsidian), every price in
 * both tiers, and the SKU large enough for a buyer to quote back over a call.
 */
export function buildLookbookHtml(
  products: ProductRow[],
  artisanName: string,
  craftCategory: string,
): string {
  const rows = products
    .map(
      (product) => `
      <div class="item">
        <img src="${product.enhanced_image_url}" alt="${escapeHtml(product.title_en)}" />
        <div class="meta">
          <div class="title-hi">${escapeHtml(product.title_hi)}</div>
          <div class="title-en">${escapeHtml(product.title_en)}</div>
          <div class="sku">SKU ${escapeHtml(product.sku)}${
            product.hsn_code ? ` · HSN ${escapeHtml(product.hsn_code)}` : ''
          }</div>
          <table>
            <tr><td>Wholesale (${product.min_wholesale_qty}+ pcs)</td><td class="price">₹${Number(
              product.recommended_wholesale_inr,
            ).toLocaleString('en-IN')}</td></tr>
            <tr><td>Retail MRP</td><td>₹${Number(
              product.recommended_retail_inr,
            ).toLocaleString('en-IN')}</td></tr>
            <tr><td>In stock</td><td>${product.stock_quantity}</td></tr>
            <tr><td>Size</td><td>${product.dimensions_cm.length} × ${
              product.dimensions_cm.width
            } cm</td></tr>
          </table>
          <div class="desc">${escapeHtml(product.description_en.slice(0, 320))}</div>
        </div>
      </div>`,
    )
    .join('');

  return `<!doctype html>
<html><head><meta charset="utf-8" />
<style>
  @page { size: A4; margin: 14mm; }
  body { font-family: -apple-system, 'Helvetica Neue', sans-serif; color: #11150E; }
  header { border-bottom: 3px solid #A8EB34; padding-bottom: 10px; margin-bottom: 18px; }
  h1 { font-size: 26px; margin: 0 0 4px; letter-spacing: -0.5px; }
  .sub { color: #5c6652; font-size: 12px; }
  .item { display: flex; gap: 14px; padding: 14px 0; border-bottom: 1px solid #e2e6dd; page-break-inside: avoid; }
  .item img { width: 132px; height: 132px; object-fit: contain; background: #f6f8f3; border-radius: 10px; }
  .meta { flex: 1; }
  .title-hi { font-size: 16px; font-weight: 700; }
  .title-en { font-size: 13px; color: #3d4536; margin-top: 2px; }
  .sku { font-size: 10px; color: #7b8471; letter-spacing: 0.6px; margin: 6px 0 8px; }
  table { font-size: 11px; border-collapse: collapse; width: 100%; max-width: 320px; }
  td { padding: 2px 0; color: #3d4536; }
  td + td { text-align: right; font-weight: 600; }
  .price { color: #4e7a0d; font-size: 13px; }
  .desc { font-size: 10px; color: #6b7462; margin-top: 8px; line-height: 1.45; }
  footer { margin-top: 20px; font-size: 10px; color: #7b8471; }
</style></head>
<body>
  <header>
    <h1>${escapeHtml(artisanName)} · Wholesale Lookbook</h1>
    <div class="sub">${escapeHtml(craftCategory)} · ${products.length} products · Prices in INR, ex-works · Generated by KalaSetu AI</div>
  </header>
  ${rows}
  <footer>All items handmade. Lead time 3-7 days. Minimum order quantities as listed per item.</footer>
</body></html>`;
}

/** Printable 2x3 inch trade-fair tag. */
export function buildQrTagHtml(
  tag: { sku: string; title_en: string; wholesale_inr: number; retail_inr: number; qr_png_data_url: string },
  product: ProductRow,
): string {
  return `<!doctype html>
<html><head><meta charset="utf-8" />
<style>
  @page { size: 2in 3in; margin: 4mm; }
  body { font-family: -apple-system, sans-serif; text-align: center; color: #060705; }
  img { width: 112px; height: 112px; }
  .hi { font-size: 11px; font-weight: 700; margin-top: 4px; }
  .en { font-size: 8px; color: #555; }
  .sku { font-size: 9px; letter-spacing: 1px; margin-top: 4px; }
  .price { font-size: 13px; font-weight: 700; margin-top: 4px; }
</style></head>
<body>
  <img src="${tag.qr_png_data_url}" alt="QR code for ${escapeHtml(tag.sku)}" />
  <div class="hi">${escapeHtml(product.title_hi)}</div>
  <div class="en">${escapeHtml(tag.title_en)}</div>
  <div class="sku">${escapeHtml(tag.sku)}</div>
  <div class="price">₹${Number(tag.retail_inr).toLocaleString('en-IN')}</div>
</body></html>`;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
